// The mark for a lab (as named by `modelVendor` or `clientMaker`) or an app (a client label). When
// `name` has no mark, `fallback` is tried, for example a client's maker. Renders nothing if neither has
// a mark, such as "Open weights".
export default function BrandLogo({
    name,
    fallback,
    className = 'size-4',
}: {
    name: string
    fallback?: string
    className?: string
}): JSX.Element | null {
    if (name === 'Custom code') return <IconLaptop className={`shrink-0 ${className}`} aria-label={name} />
    const label = MARKS[name] ? name : fallback
    const mark = label ? MARKS[label] : undefined
    if (!label || !mark) return null
    return (
        <svg
            role="img"
            aria-label={label}
            viewBox="0 0 24 24"
            className={`shrink-0 ${className}`}
            fill={mark.color ?? 'currentColor'}
            fillRule={mark.evenOdd ? 'evenodd' : undefined}
        >
            {mark.paths.map((d) => (
                <path key={d} d={d} />
            ))}
        </svg>
    )
}
